"""Real Godot 4 headless import and SpriteFrames/AnimatedSprite2D verification smoke test."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any


def find_godot_binary() -> str | None:
    """Locate a Godot 4 executable via GODOT_BIN env var or system PATH."""
    env_bin = os.environ.get("GODOT_BIN")
    if env_bin and Path(env_bin).is_file():
        return env_bin
    for candidate in ("godot4", "godot", "Godot_v4.3-stable_linux.x86_64"):
        found = shutil.which(candidate)
        if found:
            return found
    return None


def prepare_godot_project_files(godot_dir: Path, character_name: str) -> dict[str, Path]:
    """Write minimal Godot 4 project.godot and headless verification script inside godot_dir."""
    godot_dir.mkdir(parents=True, exist_ok=True)
    project_file = godot_dir / "project.godot"
    script_file = godot_dir / "verify_import.gd"

    project_text = (
        "; Engine configuration file.\n"
        "; Generated by Character Forge Studio for Godot 4 headless smoke testing.\n\n"
        "config_version=5\n\n"
        "[application]\n\n"
        f'config/name="CharacterForgeSmoke_{character_name}"\n'
        'config/features=PackedStringArray("4.3")\n\n'
        "[rendering]\n\n"
        "textures/canvas_textures/default_texture_filter=0\n"
    )
    project_file.write_text(project_text, encoding="utf-8")

    gdscript_text = f"""extends SceneTree

func _init() -> void:
\tvar tres_path := "res://{character_name}.tres"
\tvar tscn_path := "res://{character_name}.tscn"
\tvar frames_res := load(tres_path) as SpriteFrames
\tif frames_res == null:
\t\tpush_error("Failed to load SpriteFrames: " + tres_path)
\t\tquit(1)
\t\treturn
\tvar anim_names := frames_res.get_animation_names()
\tif anim_names.size() == 0:
\t\tpush_error("SpriteFrames has zero animations")
\t\tquit(2)
\t\treturn
\tvar default_anim := String(anim_names[0])
\tvar frame_count := frames_res.get_frame_count(default_anim)
\tif frame_count <= 0:
\t\tpush_error("Animation has zero frames: " + default_anim)
\t\tquit(3)
\t\treturn
\tvar tex := frames_res.get_frame_texture(default_anim, 0)
\tif tex == null or tex.get_width() <= 0 or tex.get_height() <= 0:
\t\tpush_error("Invalid frame 0 texture")
\t\tquit(4)
\t\treturn
\tvar packed_scene := load(tscn_path) as PackedScene
\tif packed_scene == null:
\t\tpush_error("Failed to load PackedScene: " + tscn_path)
\t\tquit(5)
\t\treturn
\tvar node := packed_scene.instantiate()
\tif node == null or not (node is AnimatedSprite2D):
\t\tpush_error("Root node is not AnimatedSprite2D")
\t\tquit(6)
\t\treturn
\tvar sprite_node := node as AnimatedSprite2D
\tvar summary := {{
\t\t"loaded_tres": tres_path,
\t\t"loaded_tscn": tscn_path,
\t\t"animations": Array(anim_names),
\t\t"default_animation": default_anim,
\t\t"frame_count": frame_count,
\t\t"speed_fps": frames_res.get_animation_speed(default_anim),
\t\t"frame_0_size": [tex.get_width(), tex.get_height()],
\t\t"node_name": String(sprite_node.name),
\t\t"offset": [sprite_node.offset.x, sprite_node.offset.y],
\t\t"texture_filter": int(sprite_node.texture_filter)
\t}}
\tprint("GODOT_SMOKE_JSON:" + JSON.stringify(summary))
\tnode.free()
\tquit(0)
"""
    script_file.write_text(gdscript_text, encoding="utf-8")
    return {"project_godot": project_file, "verify_script": script_file}


def run_godot_import_smoke_test(
    godot_dir: str | Path,
    character_name: str,
    *,
    force_godot_bin: str | None = None,
) -> dict[str, Any]:
    """Execute a real Godot 4 headless import and resource verification smoke test.

    If Godot 4 is unavailable on the system, explicitly returns status='blocked'
    without faking success.
    """
    target_dir = Path(godot_dir).resolve()
    files = prepare_godot_project_files(target_dir, character_name)
    godot_bin = force_godot_bin if force_godot_bin is not None else find_godot_binary()

    if not godot_bin or not Path(godot_bin).is_file():
        return {
            "schema": "character-forge.godot_smoke.v1",
            "status": "blocked",
            "verdict": "NOT ASSESSED",
            "godot_binary_available": False,
            "godot_binary": godot_bin,
            "reason": "Godot 4 binary is not available in PATH or GODOT_BIN. Prepared project.godot and verify_import.gd for offline execution.",
            "prepared_files": {k: str(v) for k, v in files.items()},
        }

    version_proc = subprocess.run(
        [godot_bin, "--version"],
        capture_output=True,
        text=True,
        timeout=15,
        check=False,
    )
    godot_version = version_proc.stdout.strip()

    # Step 1: Headless import pass so Godot generates .godot/imported/ textures
    import_proc = subprocess.run(
        [godot_bin, "--headless", "--path", str(target_dir), "--import"],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )

    # Step 2: Headless GDScript verification loading .tres and instantiating .tscn
    verify_proc = subprocess.run(
        [godot_bin, "--headless", "--path", str(target_dir), "--script", "res://verify_import.gd"],
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )

    smoke_payload: dict[str, Any] | None = None
    for line in verify_proc.stdout.splitlines():
        if line.startswith("GODOT_SMOKE_JSON:"):
            raw_json = line.split("GODOT_SMOKE_JSON:", 1)[1].strip()
            try:
                smoke_payload = json.loads(raw_json)
            except json.JSONDecodeError:
                smoke_payload = None

    passed = verify_proc.returncode == 0 and smoke_payload is not None
    return {
        "schema": "character-forge.godot_smoke.v1",
        "status": "passed" if passed else "failed",
        "verdict": "COMPLIANT" if passed else "NON-COMPLIANT",
        "godot_binary_available": True,
        "godot_binary": godot_bin,
        "godot_version": godot_version,
        "import_exit_code": import_proc.returncode,
        "verify_exit_code": verify_proc.returncode,
        "engine_verification": smoke_payload,
        "stdout": verify_proc.stdout.strip(),
        "stderr": verify_proc.stderr.strip(),
    }
